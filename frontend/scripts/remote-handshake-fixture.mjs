// Writes shared/contracts/remote/handshake-fixture.json: a handshake proof signed by
// WebCrypto exactly as a device signs it. Core's tests verify this signature with the
// Python verifier, so a format drift on either side fails a test.
// Usage: node --experimental-transform-types scripts/remote-handshake-fixture.mjs
import { writeFileSync } from "node:fs";

import { proofMessage, signProof, publicJwk } from "../src/lib/remote/identity.ts";

const subtle = globalThis.crypto.subtle;
const keys = await subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, false, ["sign", "verify"]);
const fixture = {
  note: "Generated by frontend/scripts/remote-handshake-fixture.mjs with WebCrypto. Test data only; the private key was never exported.",
  device_id: "0f8fad5b-d9cb-469f-a165-70867728950e",
  nonce: "fixture-nonce-0123456789abcdef",
  scopes: ["spatial.view", "spatial.control", "voice.spatial"],
  public_jwk: await publicJwk(keys, subtle),
};
fixture.message = proofMessage(fixture.device_id, fixture.nonce, fixture.scopes);
fixture.signature = await signProof(keys, fixture.device_id, fixture.nonce, fixture.scopes, subtle);
fixture.message_all_scopes = proofMessage(fixture.device_id, fixture.nonce, null);
fixture.signature_all_scopes = await signProof(keys, fixture.device_id, fixture.nonce, null, subtle);
writeFileSync(new URL("../../shared/contracts/remote/handshake-fixture.json", import.meta.url), JSON.stringify(fixture, null, 2) + "\n");
console.log("wrote handshake-fixture.json");
